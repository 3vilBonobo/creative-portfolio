export interface NonogramPicture {
  name: string;
  rows: string[];
}

// Author designs at 7×7, then scale each pixel to 2×2 and center it in a 15×15 board.
// This keeps the catalog readable while producing satisfyingly large daily puzzles.
function art(name: string, source: string[]): NonogramPicture {
  const doubled = source.flatMap((row) => [row, row].map((line) => [...line].flatMap((cell) => [cell, cell]).join("")));
  return { name, rows: doubled.map((row) => `0${row}`).concat("0".repeat(15)) };
}

